"use client";

import React from "react";
import { Button } from "@/components/ui/button";
import { Printer, Download } from "lucide-react";

export function PdfPrintButton({
  imageUrl,
  title,
  instructions,
  ageBand,
}: {
  imageUrl: string;
  title: string;
  instructions: string;
  ageBand?: string;
}) {
  function handlePrint() {
    // Open a print-friendly window
    const w = window.open("", "_blank");
    if (!w) return;
    const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
    w.document.write(`<!doctype html><html><head><meta charset="utf-8" /><title>${esc(title)} — Aruga</title>
    <style>
      @page { size: A4 portrait; margin: 12mm; }
      body { font-family: Inter, system-ui, sans-serif; color: #18181b; margin: 0; padding: 16px; }
      .header { border-bottom: 2px solid #14b8a6; padding-bottom: 10px; margin-bottom: 12px; }
      .brand { font-size: 11px; color: #71717b; letter-spacing: .08em; text-transform: uppercase; }
      h1 { font-size: 18px; margin: 4px 0; }
      .instructions { font-size: 11px; background: #f4f4f5; border: 1px solid #e4e4e7; border-radius: 8px; padding: 10px 12px; line-height: 1.6; }
      .art { margin-top: 14px; text-align: center; }
      .art img { max-width: 100%; height: auto; border: 1px solid #e4e4e7; border-radius: 8px; }
      .footer { margin-top: 16px; font-size: 9px; color: #71717b; text-align: center; border-top: 1px solid #e4e4e7; padding-top: 8px; }
      @media print { body { padding: 0; } }
    </style></head><body>
    <div class="header"><div class="brand">Aruga — Home Program Activity • ${esc(ageBand || "")}</div><h1>${esc(title)}</h1></div>
    <div class="instructions"><strong>Instructions:</strong> ${esc(instructions)}</div>
    <div class="art"><img src="${imageUrl}" alt="worksheet" /></div>
    <div class="footer">Generated by Aruga with Muse Spark + Muse Image • Complete digitally in-app or print and upload a photo afterwards.</div>
    <script>window.onload=()=>{ setTimeout(()=>window.print(), 300); }<\/script>
    </body></html>`);
    w.document.close();
  }

  async function handleDownload() {
    try {
      const safeName = (title || "worksheet").replace(/[^a-z0-9]+/gi, "-").replace(/^-|-$/g, "").slice(0, 60) || "worksheet";
      // data: URL can be downloaded directly
      if (imageUrl.startsWith("data:")) {
        const a = document.createElement("a");
        a.href = imageUrl;
        a.download = `${safeName}.png`;
        document.body.appendChild(a);
        a.click();
        a.remove();
        return;
      }
      // Try fetch as blob for http(s) URLs (handles CORS-friendly images)
      try {
        const res = await fetch(imageUrl);
        if (!res.ok) throw new Error(String(res.status));
        const blob = await res.blob();
        const ext = blob.type.includes("png") ? "png" : blob.type.includes("jpeg") || blob.type.includes("jpg") ? "jpg" : blob.type.includes("webp") ? "webp" : "png";
        const url = URL.createObjectURL(blob);
        const a = document.createElement("a");
        a.href = url;
        a.download = `${safeName}.${ext}`;
        document.body.appendChild(a);
        a.click();
        a.remove();
        setTimeout(() => URL.revokeObjectURL(url), 1000);
        return;
      } catch {
        // fallback: open in new tab
        window.open(imageUrl, "_blank");
      }
    } catch {
      window.open(imageUrl, "_blank");
    }
  }

  return (
    <div className="flex items-center gap-2">
      <Button type="button" variant="outline" size="sm" onClick={handlePrint} className="gap-1.5 text-xs h-8">
        <Printer className="w-3.5 h-3.5" /> Print / PDF
      </Button>
      <Button type="button" variant="ghost" size="sm" onClick={handleDownload} className="gap-1.5 text-xs h-8">
        <Download className="w-3.5 h-3.5" /> Save
      </Button>
    </div>
  );
}
